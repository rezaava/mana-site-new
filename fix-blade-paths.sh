#!/bin/bash

# ============================================
# اسکریپت اصلاح خودکار مسیرهای استاتیک در Blade
# تبدیل مسیرهای معمولی به asset()
# ============================================

echo "========================================="
echo "  اصلاح مسیرهای استاتیک در فایل‌های Blade"
echo "========================================="
echo ""

# رنگ‌ها
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

# ============================================
# پیدا کردن همه فایل‌های Blade
# ============================================
echo -e "${YELLOW}جستجوی فایل‌های Blade...${NC}"
echo ""

# لیست همه فایل‌های بلید
blade_files=$(find mana/ resources/views/ -name "*.blade.php" -type f 2>/dev/null)

if [ -z "$blade_files" ]; then
    echo -e "${RED}❌ هیچ فایل Blade ای یافت نشد!${NC}"
    exit 1
fi

echo -e "${GREEN}✅ ${#blade_files[@]} فایل Blade پیدا شد${NC}"
echo ""

# ============================================
# اصلاح هر فایل
# ============================================
count=0
for file in $blade_files; do
    echo -e "${YELLOW}🔧 در حال بررسی: $file${NC}"
    
    # پشتیبان‌گیری از فایل اصلی
    cp "$file" "$file.bak"
    
    # ============================================
    # 1. اصلاح مسیرهای CSS در <link>
    # ============================================
    # قبل: href="css/xxx.css"
    # بعد: href="{{ asset('css/xxx.css') }}"
    sed -i 's|href="css/|href="{{ asset('\''css/'\''|g' "$file"
    
    # ============================================
    # 2. اصلاح مسیرهای JS در <script>
    # ============================================
    # قبل: src="js/xxx.js"
    # بعد: src="{{ asset('js/xxx.js') }}"
    sed -i 's|src="js/|src="{{ asset('\''js/'\''|g' "$file"
    
    # ============================================
    # 3. اصلاح مسیرهای تصاویر در <img>
    # ============================================
    # قبل: src="img/xxx.png"
    # بعد: src="{{ asset('img/xxx.png') }}"
    sed -i 's|src="img/|src="{{ asset('\''img/'\''|g' "$file"
    
    # ============================================
    # 4. بستن پرانتزهای asset (رفع موارد ناقص)
    # ============================================
    # تبدیل: {{ asset('css/file.css" به {{ asset('css/file.css') }}
    sed -i "s|{{ asset('\([^']*\)\"|{{ asset('\1') }}\"|g" "$file"
    sed -i "s|{{ asset('\([^']*\)'|{{ asset('\1') }}|g" "$file"
    
    # ============================================
    # 5. اصلاح مواردی که دو بار asset شده‌اند
    # ============================================
    # تبدیل: {{ asset('{{ asset(' به {{ asset('
    sed -i "s|{{ asset('{{ asset('|{{ asset('|g" "$file"
    sed -i "s|') }}) }}|') }}|g" "$file"
    
    # ============================================
    # 6. اصلاح مسیرهای فایل‌های CSS با @import
    # ============================================
    sed -i 's|@import "css/|@import "{{ asset('\''css/'\''|g' "$file"
    sed -i "s|@import \"{{ asset('\([^']*\)\"|@import \"{{ asset('\1') }}\"|g" "$file"
    
    count=$((count + 1))
    echo -e "${GREEN}✅ اصلاح شد: $file${NC}"
    echo ""
done

# ============================================
# نمایش لیست فایل‌های اصلاح شده
# ============================================
echo "========================================="
echo -e "${GREEN}✅ ${count} فایل Blade با موفقیت اصلاح شدند!${NC}"
echo "========================================="
echo ""
echo "📁 فایل‌های اصلاح شده:"
echo ""

for file in $blade_files; do
    echo "  - $file"
done

echo ""
echo "========================================="
echo "🔍 نکات مهم:"
echo "  1. فایل‌های پشتیبان با پسوند .bak ذخیره شدند"
echo "  2. اگر مشکلی بود، می‌تونی برگردونی:"
echo "     cp \"\$file.bak\" \"\$file\""
echo "  3. حالا سایت رو ریفرش کن و ببین"
echo "========================================="